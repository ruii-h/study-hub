// One-off: turns the extracted pieces of each original guide into src/courses/<id>/*
// Usage: node tools/gen-courses.mjs   (expects ./_extract/<id>/{engine.js,data.json,style0.css,body.html})
import fs from 'node:fs';
import * as acorn from 'acorn';

for (const id of ['algo', 'bpas', 'idp']) {
  const dir = `_extract/${id}`;
  let code = fs.readFileSync(`${dir}/engine.js`, 'utf8').replace(/\r/g, '');

  // 1. Lazy-load Mermaid instead of relying on an embedded 3 MB bundle
  const mmOld = "if(!bl.length||!window.mermaid)return;";
  if (!code.includes(mmOld)) throw new Error(id + ': mm() pattern not found');
  code = code.replace(mmOld, "if(!bl.length)return;if(!window.mermaid){__api.loadMermaid().then(m=>{window.mermaid=m;mm()});return}");

  // 2. Track global listeners/observers so they can be removed when leaving the course
  code = code
    .replace(/document\.addEventListener\(/g, '__L(document,')
    .replace(/visualViewport\.addEventListener\(/g, '__L(window.visualViewport,')
    .replace(/(?<![.\w])addEventListener\(/g, '__L(window,')
    .replace(/new MutationObserver\(/g, '__MO(');

  // 3. Top-level bindings must stay reachable from inline onclick="..." handlers inside lesson HTML
  const ast = acorn.parse(code, { ecmaVersion: 'latest', sourceType: 'script' });
  const names = new Set();
  const consts = new Set();
  const pat = (p) => {
    if (p.type === 'Identifier') names.add(p.name);
    else if (p.type === 'ObjectPattern') p.properties.forEach((x) => pat(x.value || x.argument));
    else if (p.type === 'ArrayPattern') p.elements.forEach((x) => x && pat(x));
    else if (p.type === 'AssignmentPattern') pat(p.left);
    else if (p.type === 'RestElement') pat(p.argument);
  };
  for (const n of ast.body) {
    if (n.type === 'FunctionDeclaration') names.add(n.id.name);
    if (n.type === 'VariableDeclaration') n.declarations.forEach((d) => { const before = new Set(names); pat(d.id); if (n.kind === 'const') names.forEach((x) => { if (!before.has(x)) consts.add(x); }); });
  }
  names.delete('D');
  const list = [...names].filter((n) => !/^(\$|\$\$)$/.test(n));

  const out = `// Generated by tools/gen-courses.mjs from the original ${id.toUpperCase()} study guide. Behaviour is unchanged.
/* eslint-disable */
export default function mountCourse(D, __api) {
  const __undo = [];
  const __L = (t, ev, fn, o) => { t.addEventListener(ev, fn, o); __undo.push(() => t.removeEventListener(ev, fn, o)); };
  const __MO = (cb) => { const o = new MutationObserver(cb); __undo.push(() => o.disconnect()); return o; };
${code}
  // expose bindings for inline handlers (onclick="loadTheory(3)", onclick="pqMode='hard'" ...)
  const __names = {
${list.map((n) => `    ${JSON.stringify(n)}: { configurable: true, get: () => ${n}, ${consts.has(n) ? '' : `set: (v) => { ${n} = v; }`} },`).join('\n')}
  };
  for (const k of Object.keys(__names)) {
    try { Object.defineProperty(window, k, __names[k]); } catch (e) {}
  }
  return () => {
    __undo.forEach((f) => { try { f(); } catch (e) {} });
    for (const k of Object.keys(__names)) { try { delete window[k]; } catch (e) {} }
    try { delete window._sv; } catch (e) {}
  };
}
`;
  const o = `src/courses/${id}`;
  fs.writeFileSync(`${o}/engine.js`, out);
  fs.copyFileSync(`${dir}/data.json`, `${o}/data.json`);

  let css = fs.readFileSync(`${dir}/style0.css`, 'utf8');
  if (id === 'bpas') {
    const i = css.indexOf('@font-face');
    css = css.slice(0, i); // everything after is the embedded KaTeX CSS (+fonts), replaced by the katex package
  }
  fs.writeFileSync(`${o}/style.css`, css);

  let body = fs.readFileSync(`${dir}/body.html`, 'utf8').replace('<!--SCRIPT-->', '').replace(/\r/g, '');
  if (!body.includes('<div class="logo">')) throw new Error(id + ': logo not found');
  body = body.replace('<div class="logo">', '<a class="hubback" href="#/" aria-label="Back to all courses" title="All courses">⌂</a><div class="logo">');
  fs.writeFileSync(`${o}/shell.html`, body);
  console.log(id, 'bindings:', list.length, 'engine', out.length, 'css', css.length);
}
